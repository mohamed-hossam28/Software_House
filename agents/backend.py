"""
agents/backend.py
─────────────────
Backend Agent — runs after the Planner Agent.

Input:  ProjectState.tasks          (TaskList — generated by Planner)
        ProjectState.code_manifest  (CodeManifest — files to be written)
        ProjectState.architecture   (ArchData — tech stack + contracts)
Output: ProjectState.generated_code.backend (dict of path -> code)
        ProjectState.code_manifest  (marked as written with class/function definitions)

Execution model:
  - Groups backend tasks into dependency-based stages.
  - Files in the same stage have no shared dependencies and execute in parallel.
  - Concurrency is capped at MAX_PARALLEL_CALLS = 3.
  - For each file, the agent uses LLM to generate implementation and manifest summaries.
  - Code is written to ProjectState.generated_code.backend and local disk.
  - CodeManifest is updated with the returned classes and functions.
"""

