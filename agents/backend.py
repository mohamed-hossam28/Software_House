# ── System Prompt Builder ──────────────────────────────────────────────────────
def _build_system_prompt(backend_tech: str) -> str:
    """Builds a system prompt tailored to the specific backend technology from the tech stack."""
    return f"""\
You are an expert backend engineer specializing in {backend_tech}.
Your job is to generate the complete source code for a backend file and its manifest details.

## Rules:
1. Return a single valid JSON object containing "code", "classes", and "functions". No prose outside the JSON.
2. The "code" string must be complete, syntax-valid source code ready to write to disk. No placeholders, no TODOs.
3. You MUST define and export all classes and functions listed in the "Required Exports" list.
4. You must NOT import from any file path not listed in the Project Code Manifest.
5. All imports/requires must follow standard patterns for {backend_tech} based on the file paths in the manifest.
6. Follow the API contracts exactly (HTTP methods, paths, request/response models).
7. Write clean, idiomatic code utilizing features of {backend_tech}.
8. Include robust error handling and return appropriate error responses / HTTP status codes for {backend_tech}.
Return JSON: {{"code":"<full source>","classes":[{{"name":"<class name>","arguments":[{{"name":"<param>","type":"<type>","default":""}}],"docstring":"<desc>"}}],"functions":[{{"name":"<func name>","arguments":[{{"name":"<param>","type":"<type>","default":""}}],"return_type":"<type>","docstring":"<desc>"}}]}}
"""


# ── Helpers ───────────────────────────────────────────────────────────────────

def resolve_backend_stages(tasks: list[Task]) -> list[list[Task]]:
    """
    Sorts backend tasks into execution stages based on their dependencies.
    Tasks in the same stage have no dependencies on each other and can be run in parallel.
    """
    task_map = {t.id: t for t in tasks}
    backend_ids = set(task_map.keys())
    
    stages: list[list[Task]] = []
    visited: set[str] = set()
    remaining = list(tasks)
    
    while remaining:
        current_stage: list[Task] = []
        for task in remaining:
            # A backend task is ready to run if all its backend dependencies are already completed
            be_deps = [d for d in task.depends_on if d in backend_ids]
            if all(d in visited for d in be_deps):
                current_stage.append(task)
                
        if not current_stage:
            # Cycle detected or unreachable tasks — package remaining together to avoid deadlock
            stages.append(remaining)
            break
            
        stages.append(current_stage)
        for task in current_stage:
            visited.add(task.id)
            remaining.remove(task)
            
    return stages


def _build_file_prompt(
    filepath: str,
    manifest: CodeManifest,
    arch: Any,
    task: Task | None = None,
) -> str:
    """Builds a highly descriptive prompt for the LLM to implement a single backend file."""
    file_manifest = manifest.files.get(filepath)
    if not file_manifest:
        raise ValueError(f"File {filepath} not found in manifest.")
        
    # 1. Filter manifest to only actual depends_on files
    dep_files = filter_manifest_by_dependencies(manifest, filepath, task)

    manifest_entries = []
    for path, fm in dep_files.items():
        status = "written" if fm.written else "pending"
        exports_str = ", ".join(fm.exports) or "(none)"
        manifest_entries.append(
            f"- `{path}` ({status})\n"
            f"  Purpose: {fm.purpose}\n"
            f"  Exports: {exports_str}"
        )
    manifest_str = "\n".join(manifest_entries) or "No relevant dependency files in manifest."

    # Format details of already written files
    written_summaries = []
    for path, fm in dep_files.items():
        if not fm.written:
            continue
        summaries = []
        for cls in fm.classes:
            args = ", ".join(f"{a.name}: {a.type}" for a in cls.arguments)
            summaries.append(f"    - class {cls.name}({args}): {cls.docstring}")
        for func in fm.functions:
            args = ", ".join(f"{a.name}: {a.type}" for a in func.arguments)
            summaries.append(f"    - def {func.name}({args}) -> {func.return_type}: {func.docstring}")
        
        written_summaries.append(
            f"File `{path}`:\n" + ("\n".join(summaries) or "    (No class/function details)")
        )
    written_str = "\n\n".join(written_summaries) or "No relevant dependent modules written yet."

    # 2. Filter API contracts to only relevant endpoints
    contracts_str = ""
    raw_contracts = getattr(arch, 'api_contracts', []) or []
    rel_contracts = filter_api_contracts_by_relevance(
        raw_contracts,
        filepath=filepath,
        purpose=file_manifest.purpose,
        task_title=task.title if task else "",
    )
    if rel_contracts:
        lines = []
        for c in rel_contracts:
            lock = "🔒" if getattr(c, 'auth_required', False) else "🔓"
            lines.append(
                f"- {lock} {c.method} {c.path}\n"
                f"  Description: {c.description}\n"
                f"  Request Body: {c.request_body}\n"
                f"  Response Body: {c.response_body}"
            )
        contracts_str = "\n".join(lines)
    else:
        contracts_str = "No relevant API contracts specified."

    # Tech stack
    tech_stack_str = ""
    if hasattr(arch, 'tech_stack') and arch.tech_stack:
        tech_stack_str = "\n".join(f"  {k}: {v}" for k, v in arch.tech_stack.items())
    else:
        tech_stack_str = "No tech stack specified."

    user_prompt = f"""\
## File to Generate
- **File Path**: `{filepath}`
- **Purpose**: {file_manifest.purpose}
- **Required Exports**: {', '.join(file_manifest.exports) or '(none)'}
  *(CRITICAL: The generated code MUST define and export these exact names with the exact arguments expected by other modules.)*

## Architecture Context
### Tech Stack
{tech_stack_str}

### Database Schema Overview
{getattr(arch, 'database_schema_overview', 'No DB schema provided.')}

### API Contracts
{contracts_str}

## Project Code Manifest (Other Files)
Use this manifest to understand how to import from and communicate with other modules.
**RULE**: Never import from a file path not in this list.

{manifest_str}

### Details of Already Written Modules
Use these exact signatures when calling methods/functions from other modules.

{written_str}

---

Please write the complete code for `{filepath}` and summarize its classes and functions.
Respond with a single valid JSON object containing "code", "classes", and "functions".
```json
"""
    return user_prompt


OUTPUT_DIR = "output"

def write_code_to_disk(filepath: str, code: str) -> None:
    """Safely writes the generated code to the project output directory."""
    root_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    rel = filepath.lstrip("/").lstrip("\\")
    if not rel.startswith(OUTPUT_DIR + "/") and not rel.startswith(OUTPUT_DIR + "\\") and rel != OUTPUT_DIR:
        rel = os.path.join(OUTPUT_DIR, rel)
    abs_path = os.path.join(root_dir, rel)
    os.makedirs(os.path.dirname(abs_path), exist_ok=True)
    with open(abs_path, "w", encoding="utf-8") as f:
        f.write(code)


