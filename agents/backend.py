class BackendAgent(BaseAgent):
    """
    Staged parallel backend coding agent.
    """

    @property
    def system_prompt(self) -> str:
        return "You are an expert backend engineer."


    def _build_batch_prompt(self, tasks: list[Task], manifest: Any, arch: Any) -> str:
        """Build a compact batch prompt for 2-3 trivial files, returning a JSON array."""
        backend_tech = arch.tech_stack.get("backend", "FastAPI") if arch.tech_stack else "FastAPI"
        entries: list[str] = []
        for task in tasks:
            fm = manifest.by_task(task.id)
            if not fm:
                continue
            exports = ", ".join(fm.exports) or "(none)"
            entries.append(
                f"### File: {fm.filepath}\n"
                f"Purpose: {fm.purpose}\n"
                f"Required Exports: {exports}"
            )
        batch_desc = "\n\n".join(entries)
        return request_header([manifest.by_task(t.id).filepath for t in tasks if manifest.by_task(t.id)]) + (
            f"Generate the following {len(tasks)} trivial/boilerplate {backend_tech} files.\n\n"
            f"{batch_desc}\n\n"
            "Return a JSON ARRAY (not object) — one element per file in the same order:\n"
            '[{"filepath":"<path>","code":"<full source>","classes":[],"functions":[]}, ...]\n'
            "```json\n"
        )

    def _process_batch(self, tasks: list[Task], state: ProjectState, lock: Lock) -> None:
        """Single LLM call for a batch of trivial files. Fan-out results per file."""
        with lock:
            manifest = state.code_manifest
            arch = state.architecture
            sys_prompt = _system_prompt_for(arch)
            user_prompt = self._build_batch_prompt(tasks, manifest, arch)

        filepaths = [manifest.by_task(t.id).filepath for t in tasks if manifest.by_task(t.id)]
        logger.info("[BackendAgent] Batch trivial call: %s", filepaths)

        try:
            raw = self._call_with_system(sys_prompt, user_prompt, agent_name="be-batch", state=state, lock=lock)
        except Exception as exc:
            logger.error("[BackendAgent] Batch LLM call failed: %s", exc)
            with lock:
                state.log_error(self.name, f"Batch LLM call failed: {exc}")
            return

        try:
            items = self._parse_batch_response(raw)
        except Exception as exc:
            logger.error("[BackendAgent] Batch JSON parse failed: %s — raw: %s", exc, raw[:300])
            with lock:
                state.log_error(self.name, f"Batch JSON parse failed: {exc}")
            return

        aligned = align_batch_items(items, tasks, manifest)
        if aligned is None:
            logger.warning(
                "[BackendAgent] Batch response count mismatch (%d items for %d tasks) — falling back to per-file generation",
                len(items), len(tasks),
            )
            for t in tasks:
                self._process_task(t, state, lock)
            return

        for item, task in aligned:
            with lock:
                fm = manifest.by_task(task.id)
            if not fm:
                continue
            code = str(item.get("code", "")).strip()
            if not code:
                logger.warning("[BackendAgent] Batch: empty code for %s — skipping", fm.filepath)
                continue
            classes, functions = parse_metadata(item, default_return_type="None")
            try:
                written_code = self.workspace.write(fm.filepath, code, on_corrupt=agent_refuse_corrupt(state, lock))
            except Exception as exc:
                logger.error("[BackendAgent] Batch disk write failed for %s: %s", fm.filepath, exc)
                written_code = None
            if written_code is None:
                logger.warning("[BackendAgent] Batch: corrupted content refused for %s", fm.filepath)
                continue
            code = written_code
            with lock:
                code_bucket = getattr(state.generated_code, self.code_bucket)
                code_bucket[fm.filepath] = code
                state.code_manifest.mark_written(fm.filepath, classes, functions)
            logger.info("[BackendAgent] ✓ batch trivial: %s", fm.filepath)

    def _process_task(self, task: Task, state: ProjectState, lock: Lock) -> None:
        """Worker thread task to call the LLM, write file, and update manifest."""
        manifest = state.code_manifest

        with lock:
            file_manifest = manifest.by_task(task.id)
        if not file_manifest:
            logger.error("[BackendAgent] Task %s has no matching manifest file entry", task.id)
            with lock:
                state.log_error(self.name, f"Task {task.id} has no matching manifest entry")
            return

        filepath = file_manifest.filepath
        logger.info("[BackendAgent] Generating code for %s (task: %s) ...", filepath, task.id)

        # Planned Content (barrels, `.env.example`) is written verbatim.
        if file_manifest.planned_content is not None:
            self._write_deterministic(task.id, filepath, file_manifest.planned_content, "planned content", state, lock)
            return

        # Build prompt using current thread-safe snapshot of manifest and architecture stack
        with lock:
            arch = state.architecture

        user_prompt = _build_file_prompt(file_manifest.filepath, manifest, arch, task)

        sys_prompt = _system_prompt_for(arch)

        try:
            raw = self._call_with_system(sys_prompt, user_prompt, agent_name=f"be-{task.id[:6]}", state=state, lock=lock)
        except Exception as exc:
            logger.error("[BackendAgent] LLM call failed for %s: %s", filepath, exc)
            with lock:
                state.log_error(self.name, f"LLM call failed for {filepath}: {exc}")
            return

        try:
            data = self.extract_json_and_validate(raw, BackendSchema, state=state, lock=lock)
        except Exception:
            logger.error("[BackendAgent] JSON parse/validation failed for %s", filepath)
            with lock:
                state.log_error(self.name, f"JSON parse/validation failed for {filepath}")
            return

        code = data.get("code", "").strip()
        if not code:
            logger.error("[BackendAgent] LLM response for %s missing 'code' key", filepath)
            with lock:
                state.log_error(self.name, f"LLM response for {filepath} missing 'code'")
            return

        classes, functions = parse_metadata(data, default_return_type="None")

        # Write code to disk (safe-write guard refuses corrupted content)
        try:
            written_code = self.workspace.write(filepath, code, on_corrupt=agent_refuse_corrupt(state, lock))
        except Exception as exc:
            logger.error("[BackendAgent] Disk write failed for %s: %s", filepath, exc)
            with lock:
                state.log_error(self.name, f"Disk write failed for {filepath}: {exc}")
            written_code = None
        if written_code is None:
            logger.error("[BackendAgent] Corrupted content refused for %s — file not written", filepath)
            return
        code = written_code

        # Update ProjectState thread-safely
        with lock:
            state.generated_code.backend[filepath] = code
            state.code_manifest.mark_written(filepath, classes, functions)

        logger.info("[BackendAgent] Successfully wrote and summarized %s", filepath)

    def _work(self, ps: ProjectState) -> None:

        be_tasks = ps.tasks.by_agent("backend")
        if not be_tasks:
            logger.info("[BackendAgent] No backend tasks to execute.")
            return

        logger.info("[BackendAgent] Sorting and staging %d backend tasks ...", len(be_tasks))
        stages = resolve_backend_stages(be_tasks)
        logger.info("[BackendAgent] Scheduled into %d dependency-resolved stages.", len(stages))

        state_lock = Lock()

        for idx, stage in enumerate(stages):
            # Split stage into trivial batches (2-3 files per LLM call) + non-trivial singles.
            # Scaffold/entrypoint files are NEVER batched — they need their wiring prompt.
            def _is_batchable(t: Task) -> bool:
                fm = ps.code_manifest.by_task(t.id)
                return (
                    is_trivial_file(t, ps.code_manifest)
                    and not is_scaffold_file(getattr(fm, "filepath", ""))
                    and getattr(fm, "planned_content", None) is None
                )

            trivial_batch = [t for t in stage if _is_batchable(t)]
            non_trivial   = [t for t in stage if not _is_batchable(t)]
            batches    = [trivial_batch[i:i + TRIVIAL_BATCH_SIZE] for i in range(0, len(trivial_batch), TRIVIAL_BATCH_SIZE)]

            logger.info(
                "[BackendAgent] Stage %d/%d — %d trivial (→ %d batch call(s)) + %d non-trivial",
                idx + 1, len(stages), len(trivial_batch), len(batches), len(non_trivial),
            )

            with ThreadPoolExecutor(max_workers=MAX_PARALLEL_CALLS) as pool:
                futures: list[Future] = []
                for batch in batches:
                    futures.append(pool.submit(self._process_batch, batch, ps, state_lock))
                for task in non_trivial:
                    futures.append(pool.submit(self._process_task, task, ps, state_lock))

                for future in futures:
                    try:
                        future.result()
                    except Exception as exc:
                        logger.error("[BackendAgent] Task execution raised exception: %s", exc)
                        ps.log_error(self.name, f"Task execution error: {exc}")

        # Log summary
        unwritten = ps.code_manifest.unwritten()
        be_unwritten = [m for m in unwritten if m.agent == "backend"]
        logger.info(
            "[BackendAgent] Done. Written: %d backend files. Unwritten remaining: %d.",
            len(be_tasks) - len(be_unwritten),
            len(be_unwritten)
        )
