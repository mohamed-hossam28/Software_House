class BackendAgent(BaseAgent):
    """
    Staged parallel backend coding agent.
    """

    @property
    def system_prompt(self) -> str:
        return "You are an expert backend engineer."

    def _call_with_system(self, system: str, user: str, agent_name: str = "backend") -> str:
        """
        Variant of llm_call() that accepts a dedicated system prompt.
        Retries up to self.max_retries with exponential back-off.
        Returns the raw text response.
        """
        for attempt in range(1, self.max_retries + 1):
            try:
                response = self.llm_call(
                    prompt=user,
                    system_prompt=system,
                    agent_name=agent_name,
                )
                return response.text
            except Exception as exc:
                logger.warning(
                    "[BackendAgent] LLM attempt %d/%d failed: %s",
                    attempt, self.max_retries, exc,
                )
                if attempt == self.max_retries:
                    raise
                time.sleep(self.backoff * attempt)
        raise RuntimeError("Unreachable")

    def _build_prompt(self, state: ProjectState) -> str:
        raise NotImplementedError("_build_prompt is unused; run() is overridden.")

    def _parse_response(self, state: ProjectState, raw: str) -> ProjectState:
        raise NotImplementedError("_parse_response is unused; run() is overridden.")

    def _process_task(self, task: Task, state: ProjectState, lock: Lock) -> None:
        """Worker thread task to call the LLM, write file, and update manifest."""
        manifest = state.code_manifest

        with lock:
            file_manifest = manifest.by_task(task.id)
        if not file_manifest:
            logger.error("[BackendAgent] Task %s has no matching manifest file entry", task.id)
            with lock:
                state.log_error(self.name, f"Task {task.id} has no matching manifest entry")
            return

        filepath = file_manifest.filepath
        logger.info("[BackendAgent] Generating code for %s (task: %s) ...", filepath, task.id)

        # Build prompt using current thread-safe snapshot of manifest and architecture stack
        with lock:
            user_prompt = _build_file_prompt(filepath, manifest, state.architecture, task=task)
            backend_tech = "FastAPI (Python 3.12)"
            if hasattr(state.architecture, 'tech_stack') and state.architecture.tech_stack:
                backend_tech = state.architecture.tech_stack.get("backend", backend_tech)
            sys_prompt = _build_system_prompt(backend_tech)

        # Call the LLM
        try:
            raw_response = self._call_with_system(sys_prompt, user_prompt, agent_name=f"be-{task.id}")
        except Exception as exc:
            logger.error("[BackendAgent] LLM call failed for %s after retries: %s", filepath, exc)
            with lock:
                state.log_error(self.name, f"LLM call failed for {filepath}: {exc}")
            return

        # Parse JSON from raw response
        try:
            from agents.schemas.backend import BackendSchema
            data = self.extract_json_and_validate(raw_response, BackendSchema)
        except Exception as exc:
            logger.error(
                "[BackendAgent] JSON parse/validation failed for %s: %s — raw response (first 500 chars): %s",
                filepath, exc, raw_response[:500] if raw_response else "(empty)",
            )
            with lock:
                state.log_error(self.name, f"JSON parse/validation failed for {filepath}: {exc}")
            return

        code = data.get("code", "").strip()
        if not code:
            logger.error("[BackendAgent] LLM response for %s missing 'code' key", filepath)
            with lock:
                state.log_error(self.name, f"LLM response for {filepath} missing 'code'")
            return

        # Parse classes and functions from JSON response
        classes = []
        for c in data.get("classes", []):
            try:
                args = [Argument(**a) for a in c.get("arguments", [])]
                classes.append(ClassName(name=c["name"], arguments=args, docstring=c.get("docstring", "")))
            except Exception as e:
                logger.warning("[BackendAgent] Failed to parse class metadata: %s", e)

        functions = []
        for f in data.get("functions", []):
            try:
                args = [Argument(**a) for a in f.get("arguments", [])]
                functions.append(FunctionName(
                    name=f["name"],
                    arguments=args,
                    return_type=f.get("return_type", "None"),
                    docstring=f.get("docstring", "")
                ))
            except Exception as e:
                logger.warning("[BackendAgent] Failed to parse function metadata: %s", e)

        # Write code to disk
        try:
            write_code_to_disk(filepath, code)
        except Exception as exc:
            logger.error("[BackendAgent] Disk write failed for %s: %s", filepath, exc)
            with lock:
                state.log_error(self.name, f"Disk write failed for {filepath}: {exc}")
            # Continue so it's at least stored in state

        # Update ProjectState thread-safely
        with lock:
            state.generated_code.backend[filepath] = code
            state.code_manifest.mark_written(filepath, classes, functions)
            state.completed_task_ids.add(task.id)

        logger.info("[BackendAgent] Successfully wrote and summarized %s", filepath)

    def run(self, state: dict | ProjectState) -> dict[str, Any]:  # type: ignore[override]
        ps = state if isinstance(state, ProjectState) else ProjectState(**state)
        before = ps.model_copy(deep=True)
        ps.mark_agent_start(self.name)
        t0 = time.perf_counter()

        be_tasks = ps.tasks.by_agent("backend")
        if not be_tasks:
            logger.info("[BackendAgent] No backend tasks to execute.")
            return self._compute_diff(before, ps)

        logger.info("[BackendAgent] Sorting and staging %d backend tasks ...", len(be_tasks))
        stages = resolve_backend_stages(be_tasks)
        logger.info("[BackendAgent] Scheduled into %d dependency-resolved stages.", len(stages))

        state_lock = Lock()

        for idx, stage in enumerate(stages):
            if idx > 0:
                logger.info("[BackendAgent] Waiting 2s between stages to respect API rate limits ...")
                time.sleep(2)

            logger.info(
                "[BackendAgent] Executing Stage %d/%d (%d tasks in parallel) ...",
                idx + 1, len(stages), len(stage)
            )

            with ThreadPoolExecutor(max_workers=MAX_PARALLEL_CALLS) as pool:
                futures: list[Future] = []
                for task in stage:
                    task.status = "in_progress"
                    futures.append(
                        pool.submit(self._process_task, task, ps, state_lock)
                    )

                for future in futures:
                    try:
                        future.result()
                    except Exception as exc:
                        logger.error("[BackendAgent] Task execution raised exception: %s", exc)
                        ps.log_error(self.name, f"Task execution error: {exc}")

            ps.metrics.total_llm_calls += len(stage)

        duration = time.perf_counter() - t0
        ps.metrics.agent_durations[self.name] = round(duration, 3)

        # Log summary
        unwritten = ps.code_manifest.unwritten()
        be_unwritten = [m for m in unwritten if m.agent == "backend"]
        logger.info(
            "[BackendAgent] Done in %.2fs. Written: %d backend files. Unwritten remaining: %d.",
            duration,
            len(be_tasks) - len(be_unwritten),
            len(be_unwritten)
        )
        return self._compute_diff(before, ps)


